import os
import smtplib
from datetime import datetime
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from pathlib import Path
from zoneinfo import ZoneInfo

from openai import OpenAI


# =========================
# Configuration
# =========================

MODEL = os.getenv("OPENAI_MODEL", "gpt-5.5")

OUTPUT_DIR = Path("newsletters")
OUTPUT_DIR.mkdir(exist_ok=True)

client = OpenAI(
    api_key=os.environ["OPENAI_API_KEY"]
)


# =========================
# Generate newsletter
# =========================

def generate_newsletter():
    now = datetime.now(ZoneInfo("Asia/Shanghai"))
    current_date = now.strftime("%Y-%m-%d")

    prompt = f"""
Create a high-quality bilingual weekly newsletter.

Current date: {current_date}

Research the latest important developments from the past seven days.

Topics:
1. Artificial intelligence and technology
2. International news
3. Science and innovation
4. Education and English learning

Requirements:

- Search the web for current information.
- Prioritize reliable sources and recent reporting.
- Include 5 to 8 important stories.
- Explain why each story matters.
- Never invent events, statistics, quotations, or sources.
- Include source URLs for factual claims.
- Clearly distinguish confirmed facts from uncertainty.
- Avoid sensationalism and political propaganda.
- Use clear, natural Chinese and English.
- The Chinese and English versions must cover the same stories.

Output format:

# Bilingual Weekly Newsletter
Date: {current_date}

## Part 1: 中文周刊

### 本周导读
Write a short introduction.

### 本周要闻
For each story, include:
- 标题
- 发生了什么
- 为什么重要
- 信息来源及链接

### 本周科技与 AI
Summarize important developments.

### 本周英语学习
Choose 5 useful English words or expressions
from the newsletter.

For each expression, provide:
- English expression
- Chinese meaning
- An original example sentence

## Part 2: English Weekly

### Weekly Overview
Provide a concise introduction.

### Top Stories
Cover the same stories as the Chinese section.

For each story, explain:
- What happened
- Why it matters
- Source URL

### Technology and AI
Summarize important developments.

### Vocabulary Review
List the same 5 English expressions with meanings
and example sentences.

## Editorial Standards

- Keep the newsletter informative and readable.
- Prefer primary sources when available.
- Include publication dates when available.
- Provide clickable source URLs.
- Do not fabricate sources.
- Write the entire newsletter in Markdown.
"""

    response = client.responses.create(
        model=MODEL,
        tools=[
            {"type": "web_search"}
        ],
        input=prompt,
    )

    newsletter = response.output_text.strip()

    if not newsletter:
        raise RuntimeError("Newsletter generation returned empty text.")

    return current_date, newsletter


# =========================
# Save newsletter
# =========================

def save_newsletter(date, content):
    filename = OUTPUT_DIR / f"{date}.md"

    filename.write_text(
        content + "\n",
        encoding="utf-8"
    )

    print(f"Newsletter saved: {filename}")

    return filename


# =========================
# Send email
# =========================

def send_email(date, content):
    smtp_host = os.environ.get(
        "SMTP_HOST",
        "smtp.gmail.com"
    )

    smtp_port = int(
        os.environ.get("SMTP_PORT", "465")
    )

    sender = os.environ["EMAIL_FROM"]
    receiver = os.environ["EMAIL_TO"]
    password = os.environ["EMAIL_PASSWORD"]

    message = MIMEMultipart("alternative")

    message["Subject"] = (
        f"Bilingual Weekly Newsletter | {date} | "
        "中英文双语周刊"
    )

    message["From"] = sender
    message["To"] = receiver

    plain_text = f"""
Bilingual Weekly Newsletter
中英文双语周刊

Date: {date}

{content}

---
Automatically generated by GitHub Actions.
"""

    message.attach(
        MIMEText(plain_text, "plain", "utf-8")
    )

    with smtplib.SMTP_SSL(
        smtp_host,
        smtp_port,
        timeout=30
    ) as server:
        server.login(sender, password)

        server.sendmail(
            sender,
            [receiver],
            message.as_string()
        )

    print(f"Newsletter emailed to: {receiver}")


# =========================
# Main
# =========================

def main():
    print("Starting bilingual newsletter...")

    date, content = generate_newsletter()

    save_newsletter(date, content)

    send_email(date, content)

    print("Newsletter completed successfully!")


if __name__ == "__main__":
    main()